#!/usr/bin/env bash
# Generate vendor/amazon/donut in the tree: the Echo Dot (3rd gen)'s
# proprietary files from Fire OS 6 (NS6575 build 8349), each checked against
# the sha256 and size in the blobs/donut/*.txt manifests. donut-vendor.mk
# copies them into the Dot's image. Amazon's update files for this Dot have
# no public address we know, so the files come from a dump of a Dot's system
# partition, taken before anything changed it.
#
# usage: scripts/extract-donut-blobs.sh [system partition dump]
#
# Give the dump once. The script keeps a copy in the workspace, and every
# build then runs it without one (stage-tree.sh).
#
# To dump the partition from TWRP, on a Dot whose slot holds that build:
#   adb exec-out 'dd if=/dev/block/platform/soc/11120000.mmc/by-name/system_a bs=4194304 2>/dev/null' > system-dump.img
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORKSPACE_DIR="${ECHO_WORKSPACE:-$REPO_ROOT/workspace}"
TREE="${LINEAGE_TREE:-$WORKSPACE_DIR/lineage-18.1}"
OUT="$TREE/vendor/amazon/donut"

SYSTEM_IMG="$WORKSPACE_DIR/extracted/donut-fireos-ns6575-8349/system.img"
if [[ $# -eq 1 && -f "$1" ]]; then
  mkdir -p "$(dirname "$SYSTEM_IMG")"
  [[ "$(realpath "$1")" == "$(realpath -m "$SYSTEM_IMG")" ]] || cp --reflink=auto "$1" "$SYSTEM_IMG"
elif [[ $# -ne 0 ]]; then
  echo "usage: $0 [system partition dump]" >&2; exit 2
fi
[[ -f "$SYSTEM_IMG" ]] || {
  echo "ERROR: no Fire OS system image for the Echo Dot (3rd gen) yet." >&2
  echo "       Run $0 <system partition dump> once, see docs/building.md." >&2
  exit 1
}
[[ -d "$TREE/build" ]] || { echo "ERROR: LineageOS 18.1 not synced at $TREE" >&2; exit 1; }
for tool in 7z sha256sum stat rsync; do
  command -v "$tool" >/dev/null || { echo "ERROR: required tool not found: $tool" >&2; exit 1; }
done

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/proprietary"
copy_files=()

for manifest in "$REPO_ROOT"/blobs/donut/*.txt; do
while IFS=: read -r source destination expected_sha expected_size; do
  [[ -z "$source" || "$source" == \#* ]] && continue
  [[ "$destination" != /* && "$destination" != *".."* ]] || {
    echo "ERROR: unsafe destination in a manifest: $destination" >&2; exit 1;
  }
  rm -rf "$TMP/unpack"
  7z x -y -o"$TMP/unpack" "$SYSTEM_IMG" "$source" >/dev/null 2>&1 || true
  file="$TMP/unpack/$source"
  [[ -f "$file" ]] || { echo "ERROR: $source is not in the Fire OS image" >&2; exit 1; }
  [[ "$(stat -c %s "$file")" == "$expected_size" ]] || { echo "ERROR: wrong size: $source" >&2; exit 1; }
  [[ "$(sha256sum "$file" | awk '{print $1}')" == "$expected_sha" ]] || {
    echo "ERROR: sha256 mismatch: $source" >&2; exit 1;
  }
  install -D -m 0644 "$file" "$TMP/proprietary/$destination"
  copy_files+=("    vendor/amazon/donut/proprietary/$destination:\$(TARGET_COPY_OUT_SYSTEM)/$destination")
done < "$manifest"
done

{
  echo "# Generated by scripts/extract-donut-blobs.sh. Do not edit."
  echo
  echo "PRODUCT_COPY_FILES += \\"
  for ((i = 0; i < ${#copy_files[@]}; i++)); do
    if ((i + 1 < ${#copy_files[@]})); then
      echo "${copy_files[$i]} \\"
    else
      echo "${copy_files[$i]}"
    fi
  done
} >"$TMP/donut-vendor.mk"

mkdir -p "$OUT"
rsync -a --delete --checksum "$TMP/proprietary/" "$OUT/proprietary/"
install -m 0644 "$TMP/donut-vendor.mk" "$OUT/donut-vendor.mk"
echo "Extracted ${#copy_files[@]} Echo Dot (3rd gen) blobs to $OUT."
